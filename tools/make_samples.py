#!/usr/bin/env python3
"""Compile samples/SAMPLE_POSTS.md from run summaries in output/runs/ (written by tools/trigger_run.py).
Refuses runs produced by the mock LLM: samples must come from a real model."""
import glob, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
runs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(ROOT, 'output', 'runs', '*.json')), key=os.path.getmtime)]
good = [r for r in runs if r.get('post') and (r.get('result') or {}).get('status') in ('dry_run', 'published', 'scheduled')
        and (r.get('llm') or {}).get('model') not in (None, 'mock-extractive')]
if len(good) < 3:
    sys.exit(f'Only {len(good)} real-LLM runs found in output/runs (need 3). Run scripts/generate_samples.sh with a real LLM key.')
out = ['# Sample posts generated by the workflow', '',
       f"Model: {good[-1]['llm']['provider']} / {good[-1]['llm']['model']}. Each post passed both guardrails (rules + LLM review). "
       'Source URLs are real public PlacidWay pages.', '']
for i, r in enumerate(good[-3:], 1):
    g = r.get('guardrail_history') or []
    out += [f"## {i}. {r['content_type'].title()} - {r['category']}", '', f"**Source:** {r['item_url']}  ",
            f"**Image:** {r.get('image') or 'none (link post)'}  ",
            f"**Characters before link:** {r['chars_before_link']} / 500  ",
            f"**Guardrail attempts:** {len(g)} ({' -> '.join('pass' if a['rules'] and a['llm'] else 'fail' for a in g)})  ",
            f"**Execution:** #{r['execution_id']} - status `{r['result']['status']}`", '', '```text', r['post'], '```', '']
    fails = [iss for a in g for iss in a['issues']]
    if fails:
        out += ['Issues caught and fixed on the way:', ''] + [f"- [{x['by']}:{x['type']}] {x.get('excerpt','')} - {x['reason']}" for x in fails] + ['']
os.makedirs(os.path.join(ROOT, 'samples'), exist_ok=True)
open(os.path.join(ROOT, 'samples', 'SAMPLE_POSTS.md'), 'w').write('\n'.join(out))
json.dump(good[-3:], open(os.path.join(ROOT, 'samples', 'sample_runs.json'), 'w'), indent=2, ensure_ascii=False)
print('wrote samples/SAMPLE_POSTS.md and samples/sample_runs.json')
